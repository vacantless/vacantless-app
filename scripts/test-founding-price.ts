import { hasFoundingDiscount, foundingLockUntil, foundingStampMetadata } from "../lib/founding-price";
let pass = 0, fail = 0;
const ok = (c: boolean, m: string) => { if (c) pass++; else { fail++; console.log("FAIL", m); } };
ok(hasFoundingDiscount({ discounts: [{ coupon: { id: "FOUNDING50X3" } }] }), "classic coupon");
ok(hasFoundingDiscount({ discounts: [{ source: { coupon: "FOUNDING50X3", type: "coupon" } }] }), "dahlia source.coupon");
ok(hasFoundingDiscount({ discounts: [{ promotion_code: { code: "FOUNDING10" } }] }), "promo code text");
ok(hasFoundingDiscount({ discounts: [{ coupon: { id: "FOUNDING20-50X12" } }] }), "S731 Founding 20 coupon");
ok(hasFoundingDiscount({ discounts: [{ coupon: { id: "FOUNDING20-49X12" } }] }), "S731e Founding 20 flat coupon");
ok(!hasFoundingDiscount({ discounts: [{ coupon: { id: "OTHER" } }] }), "other coupon");
ok(!hasFoundingDiscount({ discounts: [] }), "no discount");
ok(!hasFoundingDiscount(null), "null");
ok(!hasFoundingDiscount({ description: "FOUNDING10 is great" }), "substring does not count");
const loop: any = { a: 1 }; loop.self = loop;
ok(!hasFoundingDiscount(loop), "cycle safe");
const oct20 = Date.UTC(2026, 9, 20) / 1000;
ok(foundingLockUntil(oct20) === "2027-10-20", "plus 12 months");
ok(foundingLockUntil(Date.UTC(2028, 1, 29) / 1000) === "2029-02-28", "Feb 29 clamps");
const sub = { discounts: [{ coupon: { id: "FOUNDING50X3" } }] };
const md = foundingStampMetadata({ subscription: sub, createdSec: oct20, existingMetadata: { org_id: "x" } });
ok(md?.founding_price === "locked" && md?.founding_price_until === "2027-10-20", "stamp");
ok(foundingStampMetadata({ subscription: sub, createdSec: oct20, existingMetadata: { founding_price: "locked" } }) === null, "already stamped");
ok(foundingStampMetadata({ subscription: {}, session: { discounts: [{ promotion_code: { code: "FOUNDING10" } }] }, createdSec: oct20, existingMetadata: {} }) !== null, "from session");
ok(foundingStampMetadata({ subscription: {}, createdSec: oct20, existingMetadata: {} }) === null, "not founding");
console.log(`founding-price: ${pass} passed, ${fail} failed`);
if (fail) process.exit(1);
