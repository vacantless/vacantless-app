import { textingRequestEmail, textingOnEmail, displayCanadianNumber } from "../lib/texting-setup-emails";
let pass = 0, fail = 0;
const ok = (c: boolean, m: string) => { if (c) pass++; else { fail++; console.log("FAIL", m); } };
const r = textingRequestEmail({ orgName: "Lakeview Rentals", orgId: "abc", requesterEmail: "a@b.com", addresses: ["1 A St, Windsor, ON", "2 B St, Windsor, ON", "3 C St", "4 D St"] });
ok(r.subject === "Texting request: Lakeview Rentals", "subject");
ok(r.body.includes("Asked by: a@b.com"), "requester");
ok(r.body.includes("1 A St, Windsor, ON") && !r.body.includes("4 D St"), "three addresses max");
ok(r.body.includes("https://app.vacantless.com/api/sms/inbound") && r.body.includes("https://app.vacantless.com/api/sms/voice"), "webhooks");
ok(r.body.includes("/dashboard/admin#texting-numbers"), "admin link");
ok(!/—/.test(r.body), "no em dash");
const e = textingRequestEmail({ orgName: null, orgId: "xyz", requesterEmail: null, addresses: [] });
ok(e.subject === "Texting request: xyz" && e.body.includes("No rentals yet"), "empty case");
ok(displayCanadianNumber("+12267980746") === "226-798-0746", "format");
ok(displayCanadianNumber("+447700900123") === "+447700900123", "non-NANP unchanged");
const o = textingOnEmail({ orgName: "Lakeview Rentals", phoneE164: "+12265550100" });
ok(o.subject === "Texting is on" && o.body.includes("226-555-0100") && o.body.includes("Lakeview Rentals"), "on email");
ok(!/—/.test(o.body), "no em dash on");
console.log(`texting-setup-emails: ${pass} passed, ${fail} failed`);
if (fail) process.exit(1);
